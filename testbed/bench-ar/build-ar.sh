#!/usr/bin/env bash
# Builds the bench for the adaptive retry comparison against the trees made by ../setup-src-ar.sh, without
# changing any valkey-go source: one generated modfile per tree (go.<tree>.mod, replace => ../src/<tree>).
#
#   bin/bench-pn, bin/bench-pn208      -tags pr1      -min-refresh, -max-slot-wait
#   bin/bench-pnbd, bin/bench-pnbdr    -tags pr1,bd   plus -lazy-max-delay
#   bin/bench-m2                       no tags        upstream main a23e130 (TREES="m2 final")
#   bin/bench-final                    -tags pr1,vd   the reworked ASM PR: -min-refresh, -max-slot-wait, -max-refresh-delay
#   bin/bench-m2vd                     -tags vd       main a23e130 + Vardhaman's fork PR #9 alone: -max-refresh-delay
#   bin/bench-r2, bin/bench-r2big      -tags pr1,vd,nsw  the PR after its second review (no MaxSlotWait):
#                                                     -min-refresh, -max-refresh-delay
#
# Works offline: GOFLAGS=-mod=mod GOPROXY=off by default.
set -euo pipefail
cd "$(dirname "$0")"
export GOFLAGS=${GOFLAGS:--mod=mod} GOPROXY=${GOPROXY:-off}
TREES=(${TREES:-pn pn208 pnbd pnbdr})
mkdir -p bin
for t in "${TREES[@]}"; do
  [[ -d ../src/$t ]] || { echo "../src/$t is missing: run ../setup-trees.sh" >&2; exit 1; }
  tags=pr1
  [[ $t == pnbd* ]] && tags=pr1,bd
  [[ $t == final* ]] && tags=pr1,vd
  [[ $t == m2 ]] && tags=""
  [[ $t == m2vd ]] && tags=vd
  [[ $t == r2* ]] && tags=pr1,vd,nsw
  { grep -v -E '^(//|replace )' go.mod; echo "// Generated by build-ar.sh: the bench built against ../src/$t."; echo "replace github.com/valkey-io/valkey-go => ../src/$t"; } >"go.$t.mod"
  cp go.sum "go.$t.sum"
  go vet -modfile="go.$t.mod" ${tags:+-tags "$tags"} .
  go build -modfile="go.$t.mod" ${tags:+-tags "$tags"} -ldflags "-X main.buildName=$t" -o "bin/.bench-$t.tmp" .
  mv -f "bin/.bench-$t.tmp" "bin/bench-$t"
  printf 'bin/bench-%-6s tags=%-7s valkey-go => %s (%s)\n' "$t" "$tags" \
    "$(go version -m "bin/bench-$t" | awk '$1 == "=>" { print $2 }')" "$(git -C "../src/$t" rev-parse --short HEAD)"
done
